function pair(item, right, other, missed) {
  const actualAnswer = item.section === 'sound' ? item.pinyin : item.target;
  return item.choices.indexOf(actualAnswer) < item.choices.indexOf(missed) ? [right, other] : [other, right];
}

function soundQuestion(item, pick) {
  const { word, target, pinyin } = item;
  const context = soundScenes[word];
  if (!context) return null;
  if (pick.correct) {
    return { kind: 'sound-write', context, prompt: `请给句中“${word}”的“${target}”注音。`,
      expected: pinyin, hint: specialComparisons[word]?.detail ?? `回想一下${familiar[pinyin]}的读音。`,
      explanation: `“${word}”的“${target}”读 ${pinyin}。` };
  }
  const uncommon = alternativeFeatures[pick.value];
  const special = specialComparisons[word];
  const feature = special?.feature ?? uncommon?.feature;
  const right = special?.right ?? familiar[pinyin];
  const other = uncommon?.other ?? familiar[pick.value];
  if (!right || !other || right === other) return null;
  const comparison = feature ? `的${feature}相同` : '同音（包括声调）';
  const hint = feature ? `先轻声读两个熟词，比较指出的字的${feature}。` : '轻声读两个熟词，留意声母、韵母和声调。';
  return { kind: 'sound-choice', prompt: `“${word}”的“${target}”与哪个熟字${comparison}？`,
    context, choices: pair(item, right, other, pick.value), expected: right, hint,
    explanation: `“${target}”在这里读 ${pinyin}，与${right}${feature ? `的${feature}相同` : '同音'}。${special?.detail ?? ''}` };
}

export function assistedQuestion(section, pick) {
  const item = pick?.item;
  if (!item || item.section !== section || (pick.correct && !pick.unsure)) return null;
  if (section === 'sound') return soundQuestion(item, pick);
  if (section !== 'spelling' || !Object.hasOwn(spellingScenes, item.word)) return null;
  const [sentence, hint] = spellingScenes[item.word];
  const { word, target } = item;
  const explanation = `“${word}”用“${target}”。${hint}`;
  if (pick.correct) {
    return { kind: 'spelling-write', prompt: `根据句意和读音 ${item.fullReading}，填入完整词语。`,
      context: sentence.replace(word, '＿'), expected: word, hint, explanation };
  }
  return { kind: 'spelling-choice', prompt: '结合句意，空缺处应填哪个字？',
    context: sentence.replace(word, word.replace(target, '＿')), choices: pair(item, target, pick.value, pick.value),
    expected: target, hint, explanation: `${explanation}“${pick.value}”用在“${spellingExamples[pick.value]}”里。` };
}
