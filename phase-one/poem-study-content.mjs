export function getStudyScene(poem, partNumber, partText) {
  if (!Number.isInteger(partNumber) || partNumber < 1 || typeof partText !== 'string') return null;
  if (!Object.hasOwn(passages, poem?.title)) return null;
  const row = passages[poem.title][partNumber - 1];
  if (!row || !partText.includes(row[0])) return null;
  const [answer, prompt, hint] = row;
  return { prompt, answer, hint };
}
